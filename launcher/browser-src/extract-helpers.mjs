#!/usr/bin/env node
// extract-helpers.mjs — generate helpers.generated.mjs by slicing the PURE
// code regions out of ../launch.mjs (program ids, rule encoders, spec
// validation, PDA derivations, engine config payload, DBC curve builder).
// The browser bundle and the equivalence harness both consume the generated
// module, so the in-browser launch sequence shares launch.mjs's code by
// construction — regenerate after any launch.mjs edit:
//   node extract-helpers.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.join(here, '..', 'launch.mjs'), 'utf8');

function slice(startMarker, endMarker) {
  const a = src.indexOf(startMarker);
  if (a < 0) throw new Error('start marker not found: ' + startMarker);
  const b = src.indexOf(endMarker, a);
  if (b < 0) throw new Error('end marker not found: ' + endMarker);
  return src.slice(a, b).replace(/\s+$/, '') + '\n';
}

const regions = [
  // program identities: ENGINE .. INIT_METAS_DISC
  slice('const ENGINE = new PublicKey(', '// ---------- measured rents'),
  // measured rents
  slice('const RENT = {', '// ---------- rule catalog'),
  // rule catalog + ruleIdOf + encodeParams + validateSpec
  slice('const RULE_NAMES = {', '// ---------- PDAs ----------'),
  // PDA derivations + account-key helper K
  slice('const pdaE =', '// ---------- engine config payload'),
  // engine config payload builder
  slice('function configPayload', '// ---------- DBC curve parameters'),
  // DBC curve parameters (buildCurve shape)
  slice('function curveConfig', '// ---------- robust sender'),
];

const header = `// GENERATED by browser-src/extract-helpers.mjs from ../launch.mjs — do not
// edit by hand; regenerate with: node extract-helpers.mjs
import { PublicKey, SystemProgram, TransactionInstruction, LAMPORTS_PER_SOL } from '@solana/web3.js';
import { TOKEN_2022_PROGRAM_ID } from '@solana/spl-token';
import { IMPLEMENTED_IDS } from './rules.generated.mjs';
import {
  buildCurve, TokenType, TokenDecimal, ActivationType, BaseFeeMode,
  CollectFeeMode, MigrationOption, MigrationFeeOption, TokenAuthorityOption,
  deriveDbcPoolAddress, deriveDbcPoolAuthority, deriveDbcTokenVaultAddress,
  derivePartnerMetadata,
} from '@meteora-ag/dynamic-bonding-curve-sdk';

`;

const exportsLine = `
export {
  ENGINE, REGISTRY, DISTRIBUTOR, DBC_ID, NATIVE_MINT, T22, INIT_METAS_DISC, HOUSE_SWAP_PROGRAM_ID,
  MEMO_PROGRAM_ID, LAUNCH_TAG_MARKER,
  RENT, RULE_NAMES, NAME_TO_ID, IMPLEMENTED, MODES,
  ruleIdOf, encodeParams, validateSpec, requiredExtras, metaListSize, metaListRent,
  resolveFees, FEE_BPS_MIN, FEE_BPS_MAX, FEE_BPS_DEFAULT,
  resolveGraduation, GRADUATION_MODES, NEVER_THRESHOLD_LAMPORTS, NEVER_THRESHOLD_SOL, resolveHouseFields, solToLamportsExact,
  resolveDevBuy, DEV_BUY_MAX_SOL,
  METADATA_BASE_DEFAULT, metadataSlug, defaultMetadataDescription, resolveMetadata,
  PARTNER_IDENTITY, partnerIdentityText, derivePartnerMetadata,
  pdaE, configPda, metaPda, pricePda, rentVaultPda, distPda, K, buildTagMemoIx,
  configPayload, curveConfig, configFieldsText,
  deriveDbcPoolAddress, deriveDbcPoolAuthority, deriveDbcTokenVaultAddress,
};
`;

const out = header + regions.join('\n') + exportsLine;
const outPath = path.join(here, 'helpers.generated.mjs');
fs.writeFileSync(outPath, out);
console.log('wrote', outPath, out.length, 'bytes');
