#!/usr/bin/env node
// gen-rules.mjs — generate launcher/browser-src/rules.generated.mjs from the
// ENGINE SOURCE (engine/src/lib.rs), the ground truth for which rules a
// config may enable.
//
//   node launcher/bin/gen-rules.mjs           regenerate the file
//
// Parsed from lib.rs:
//   * the RULE_* constants (`pub const RULE_X: u16 = N;`) — id -> const name
//   * the rule_implemented() match arms — which of those ids this engine
//     build actually enforces (known-but-unimplemented rules are rejected
//     at config-init by the engine, and shown disabled by the composer)
//
// Labels are the human names from the catalog in
// ~/workspace/taxhook/SPEC-HOOK-LAUNCHER.md §5. A RULE_* constant with no
// label here fails generation loudly — a new engine rule must get a human
// name before the composer may offer it.
//
// Output is deterministic (sorted by id, fixed formatting, no timestamps):
// running this twice produces no diff. Verify with:
//   node launcher/bin/check-rule-parity.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const ENGINE_LIB_RS = path.join(here, '..', '..', 'engine', 'src', 'lib.rs');
export const RULES_GENERATED_PATH = path.join(here, '..', 'browser-src', 'rules.generated.mjs');

// Human labels, SPEC-HOOK-LAUNCHER.md §5 order (rule_id -> label).
export const RULE_LABELS = {
  1: 'Basis Latch',
  2: 'Escrow Split',
  3: 'Agent-Only',
  4: 'App-Gated',
  5: 'Crown Beneficiary',
  6: 'Tithe Seat',
  7: 'P2P Toggle',
  8: 'Holder-Gated',
  9: 'Max Wallet',
  10: 'Allow/Blocklist',
  11: 'Grudge',
  12: 'Trading Hours',
  13: 'Vesting Clock',
  14: 'Decay Tax',
  15: 'King of the Pool',
  16: 'Buyback & Burn',
  17: 'Ecosystem Gate',
};

// Parse lib.rs -> [{ id, constName, label, implemented }] sorted by id.
// Throws on anything unexpected (unknown label, unparsable match arms) —
// generation must never silently emit a partial truth.
export function parseEngineRules(libRsSource) {
  const consts = new Map(); // constName -> id
  const constRe = /pub const (RULE_[A-Z0-9_]+): u16 = (\d+);/g;
  let m;
  while ((m = constRe.exec(libRsSource)) !== null) {
    consts.set(m[1], Number(m[2]));
  }
  if (consts.size === 0) throw new Error('gen-rules: no RULE_* constants found in engine/src/lib.rs');

  const fnStart = libRsSource.indexOf('fn rule_implemented');
  if (fnStart < 0) throw new Error('gen-rules: rule_implemented() not found in engine/src/lib.rs');
  const fnEnd = libRsSource.indexOf('\n}', fnStart);
  if (fnEnd < 0) throw new Error('gen-rules: rule_implemented() body not terminated');
  const fnBody = libRsSource.slice(fnStart, fnEnd);
  const implemented = new Set();
  const armRe = /RULE_[A-Z0-9_]+/g;
  while ((m = armRe.exec(fnBody)) !== null) {
    if (!consts.has(m[0])) throw new Error(`gen-rules: rule_implemented() names unknown constant ${m[0]}`);
    implemented.add(consts.get(m[0]));
  }
  // Bare numeric arms (defensive: a future build matching on literals).
  const numRe = /\|\s*(\d+)\b/g;
  while ((m = numRe.exec(fnBody)) !== null) implemented.add(Number(m[1]));
  if (implemented.size === 0) throw new Error('gen-rules: rule_implemented() has no match arms');

  const rules = [...consts.entries()]
    .map(([constName, id]) => {
      const label = RULE_LABELS[id];
      if (!label) throw new Error(`gen-rules: rule ${id} (${constName}) has no label — add its SPEC-HOOK-LAUNCHER.md §5 name to RULE_LABELS in gen-rules.mjs`);
      return { id, constName, label, implemented: implemented.has(id) };
    })
    .sort((a, b) => a.id - b.id);
  return rules;
}

// Render the generated module text for a parsed rule list. Pure and
// deterministic — check-rule-parity.mjs compares the on-disk file against
// exactly this string.
export function renderRulesModule(rules) {
  const implementedIds = rules.filter((r) => r.implemented).map((r) => r.id);
  const lines = [];
  lines.push('// GENERATED by launcher/bin/gen-rules.mjs from engine/src/lib.rs — do not');
  lines.push('// edit by hand; regenerate with: node launcher/bin/gen-rules.mjs');
  lines.push('// Ground truth: the RULE_* constants and the rule_implemented() match');
  lines.push('// arms in the engine source. Labels: SPEC-HOOK-LAUNCHER.md §5.');
  lines.push('');
  lines.push('export const RULES = [');
  for (const r of rules) {
    lines.push(`  { id: ${r.id}, constName: ${JSON.stringify(r.constName)}, label: ${JSON.stringify(r.label)}, implemented: ${r.implemented} },`);
  }
  lines.push('];');
  lines.push('');
  lines.push(`export const IMPLEMENTED_IDS = [${implementedIds.join(', ')}];`);
  lines.push('');
  // The pin's source of truth is launcher/engine-v4.json (maintained by
  // the deploy windows; S1 set it to the verified TAIL hash — sha256 of
  // the live engine ProgramData from offset 45 to the end of the
  // account). No valid pin recorded => null => the guard stays armed.
  let pin = null;
  try {
    const v4 = JSON.parse(fs.readFileSync(path.join(here, '..', 'engine-v4.json'), 'utf8'));
    if (typeof v4.fixedEngineSha256 === 'string' && /^[0-9a-f]{64}$/.test(v4.fixedEngineSha256)) pin = v4.fixedEngineSha256;
  } catch { /* no pin recorded — guard stays armed */ }
  lines.push('// Composer guard: while fixedEngineSha256 is null, the v4 engine crank');
  lines.push('// fix for this combination has NOT been verified live, and composers');
  lines.push('// must refuse to produce a spec that enables it. The pin is read from');
  lines.push('// launcher/engine-v4.json at generation time (the verified live hash).');
  lines.push(`export const GUARD = { combo: "basisLatch+never", fixedEngineSha256: ${pin ? JSON.stringify(pin) : 'null'} };`);
  lines.push('');
  return lines.join('\n');
}

export function generateRules() {
  const src = fs.readFileSync(ENGINE_LIB_RS, 'utf8');
  return renderRulesModule(parseEngineRules(src));
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const out = generateRules();
  fs.writeFileSync(RULES_GENERATED_PATH, out);
  const rules = parseEngineRules(fs.readFileSync(ENGINE_LIB_RS, 'utf8'));
  const impl = rules.filter((r) => r.implemented).map((r) => r.id);
  console.log(`wrote ${RULES_GENERATED_PATH} (${out.length} bytes)`);
  console.log(`rules: ${rules.length} known, implemented: {${impl.join(', ')}}`);
}
